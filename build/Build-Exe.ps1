<#
.SYNOPSIS
    Bundles Helpers.ps1 + every modules/Tweaks.*.ps1 + Start-WinMuteGui.ps1
    into one self-contained script, then compiles it to WinMute.exe with
    ps2exe. Run after any change to modules/ or the GUI, before cutting a
    release - the exe is a build artifact, not something to hand-edit.

.EXAMPLE
    Install-Module ps2exe -Scope CurrentUser  # one-time, if not already installed
    .\build\Build-Exe.ps1
#>
[CmdletBinding()]
param([string]$OutputExe = (Join-Path $PSScriptRoot 'WinMute.exe'))

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$guiPath = Join-Path $root 'Start-WinMuteGui.ps1'
$guiLines = [System.Collections.Generic.List[string]](Get-Content $guiPath)

# [CmdletBinding()]/param() must be the first statement in a script - fine in
# Start-WinMuteGui.ps1 on its own, but module code gets prepended above it in
# the bundle, so both lines are stripped (param() takes no arguments anyway).
$cmdletBindingLine = $guiLines.FindIndex([Predicate[string]] { param($l) $l.Trim() -eq '[CmdletBinding()]' })
if ($cmdletBindingLine -lt 0) { throw "Could not find [CmdletBinding()] in $guiPath - did the script change shape?" }
$guiLines.RemoveRange($cmdletBindingLine, 2)  # [CmdletBinding()], param()

# The exe requests elevation itself via ps2exe's -requireAdmin manifest flag,
# so the script's own "relaunch elevated" block (isAdmin check -> Start-Process
# -Verb RunAs -File $PSCommandPath) is unnecessary for the compiled build, and
# $PSCommandPath pointing at an .exe would break that Start-Process call anyway.
$elevateAnchor = $guiLines.FindIndex([Predicate[string]] { param($l) $l.Trim() -eq 'if (-not $isAdmin) {' })
if ($elevateAnchor -lt 1) { throw "Could not find the self-elevation block anchor in $guiPath - did the script change shape?" }
$guiLines.RemoveRange($elevateAnchor - 1, 5)  # $isAdmin=..., if (){, Start-Process, return, }

# modules/ gets inlined instead of dot-sourced from disk.
$dotSourceLine = $guiLines.FindIndex([Predicate[string]] { param($l) $l -like "*Join-Path*root*'modules'*" })
if ($dotSourceLine -lt 0) { throw "Could not find the modules/ dot-source line in $guiPath - did the script change shape?" }
$guiLines.RemoveAt($dotSourceLine)

# $PSScriptRoot is set correctly by ps2exe in recent versions, but fall back to
# the exe's own path so logs/applied.json always lands next to the exe.
$rootLine = $guiLines.FindIndex([Predicate[string]] { param($l) $l.Trim() -eq '$root = $PSScriptRoot' })
if ($rootLine -ge 0) {
    $guiLines[$rootLine] = 'if ($PSScriptRoot) { $root = $PSScriptRoot } else { $root = Split-Path -Parent ([System.Diagnostics.Process]::GetCurrentProcess().MainModule.FileName) }'
}

$moduleFiles = Get-ChildItem (Join-Path $root 'modules') -Filter '*.ps1' | Sort-Object Name

$bundle = New-Object System.Collections.Generic.List[string]
$bundle.Add('# Auto-generated by build/Build-Exe.ps1 - edit the source files in modules/ or Start-WinMuteGui.ps1 and rebuild, do not edit this output directly.')
foreach ($f in $moduleFiles) {
    $bundle.Add("# --- modules/$($f.Name) ---")
    $bundle.AddRange([string[]](Get-Content $f.FullName))
}
$bundle.Add('# --- Start-WinMuteGui.ps1 ---')
$bundle.AddRange($guiLines)

$tempPs1 = Join-Path ([System.IO.Path]::GetTempPath()) 'WinMute.bundle.ps1'
Set-Content -Path $tempPs1 -Value ($bundle -join "`r`n") -Encoding UTF8

if (-not (Get-Module -ListAvailable ps2exe)) {
    throw "ps2exe module not found. Install it once with: Install-Module ps2exe -Scope CurrentUser"
}
Import-Module ps2exe

Invoke-ps2exe -inputFile $tempPs1 -outputFile $OutputExe `
    -noConsole -requireAdmin `
    -title 'Win Mute' -product 'Win Mute' -company 'obrenoalvim' `
    -version '1.0.0.0' -copyright 'MIT License'

Remove-Item $tempPs1 -ErrorAction SilentlyContinue
Write-Host "Built $OutputExe" -ForegroundColor Green
